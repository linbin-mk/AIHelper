window.__i18nMessages._lang = 'en';
window.__i18nMessages._storedLang = 'auto';

window.t = function (key, params) {
  var msgs = window.__i18nMessages;
  var lang = msgs._lang || 'en';
  var map = msgs[lang] || msgs['en'];

  var parts = key.split('.');
  var value = map;
  for (var i = 0; i < parts.length; i++) {
    if (value == null) break;
    value = value[parts[i]];
  }

  if (typeof value !== 'string') {
    if (value !== undefined && value !== null) {
      return value;
    }
    return key;
  }

  if (params) {
    return value.replace(/\{(\w+)\}/g, function (match, paramKey) {
      return params[paramKey] != null ? params[paramKey] : match;
    });
  }

  return value;
};

window.getLanguage = async function () {
  try {
    var result = await chrome.storage.local.get('ai_helper_language');
    return result.ai_helper_language || 'auto';
  } catch (e) {
    return 'auto';
  }
};

window.resolveLanguage = function (stored) {
  if (stored === 'auto') {
    var browserLang = (navigator.language || 'en').toLowerCase();
    return browserLang.startsWith('zh') ? 'zh-CN' : 'en';
  }
  return stored;
};

window.setLanguage = async function (lang) {
  window.__i18nMessages._storedLang = lang;
  window.__i18nMessages._lang = window.resolveLanguage(lang);
  try {
    await chrome.storage.local.set({ ai_helper_language: lang });
  } catch (e) {
    // silent fail
  }
};

window.updatePageLanguage = function () {
  var lang = window.__i18nMessages._lang || 'en';
  document.documentElement.lang = lang;

  var elements = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < elements.length; i++) {
    var el = elements[i];
    var key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = window.t(key);
    }
  }

  var titleEls = document.querySelectorAll('[data-i18n-title]');
  for (var ti = 0; ti < titleEls.length; ti++) {
    var tel = titleEls[ti];
    var tkey = tel.getAttribute('data-i18n-title');
    if (tkey) {
      tel.title = window.t(tkey);
    }
  }

  var placeholderEls = document.querySelectorAll('[data-i18n-placeholder]');
  for (var j = 0; j < placeholderEls.length; j++) {
    var pel = placeholderEls[j];
    var pkey = pel.getAttribute('data-i18n-placeholder');
    if (pkey) {
      pel.placeholder = window.t(pkey);
    }
  }
};

window.initLanguage = async function () {
  var stored = await window.getLanguage();
  window.__i18nMessages._storedLang = stored;
  window.__i18nMessages._lang = window.resolveLanguage(stored);
  window.updatePageLanguage();
};
